// Embed the HTML template so Dashboard and CLI deployments use the same source.
import { readFile, writeFile } from "node:fs/promises";

const functionDirectory = new URL("../supabase/functions/resend-email/", import.meta.url);

try {
  const template = await readFile(new URL("email-template.html", functionDirectory), "utf8");
  const entry = `// Generated by scripts/build-order-email-function.mjs; edit email-template.html instead.
import { handleOrderNotification } from "./handler.ts";

const EMAIL_TEMPLATE = ${JSON.stringify(template)};

Deno.serve((request) => handleOrderNotification(request, {
  webhookSecret: Deno.env.get("ORDER_WEBHOOK_SECRET") ?? "",
  apiKey: Deno.env.get("RESEND_API_KEY") ?? "",
  from: Deno.env.get("ORDER_NOTIFICATION_FROM") ?? "",
  recipients: Deno.env.get("ORDER_NOTIFICATION_TO") ?? "",
  emailTemplate: EMAIL_TEMPLATE,
}));
`;
  if (process.argv.includes("--dashboard")) {
    const handler = await readFile(new URL("handler.ts", functionDirectory), "utf8");
    process.stdout.write(handler + "\n" + entry.replace('import { handleOrderNotification } from "./handler.ts";\n', ""));
  } else {
    await writeFile(new URL("index.ts", functionDirectory), entry);
    console.info("Updated resend-email/index.ts from email-template.html.");
  }
} catch (error) {
  console.error("Could not build the order notification function; check its handler and HTML template files.", error);
  process.exitCode = 1;
}
