// Generate a separate template module because Dashboard deployments cannot bundle static HTML.
import { readFile, writeFile } from "node:fs/promises";

const functionDirectory = new URL("../supabase/functions/resend-email/", import.meta.url);

try {
  const template = await readFile(new URL("email-template.html", functionDirectory), "utf8");
  const escapedTemplate = template.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  const templateModule = `// Generated by scripts/build-order-email-function.mjs; edit email-template.html instead.
export const EMAIL_TEMPLATE = \`${escapedTemplate}\`;
`;
  await writeFile(new URL("email-template.ts", functionDirectory), templateModule);
  if (process.argv.includes("--dashboard")) {
    const shared = await readFile(new URL("../_shared/order-delivery.ts", functionDirectory), "utf8");
    const handler = await readFile(new URL("handler.ts", functionDirectory), "utf8");
    const entry = await readFile(new URL("index.ts", functionDirectory), "utf8");
    process.stdout.write(shared + "\n" + handler.replace('import { getOrderDelivery, type DeliveryFields } from "../_shared/order-delivery.ts";\n', "") + "\n" + entry.replace('import { handleOrderNotification } from "./handler.ts";\n', ""));
  } else {
    console.info("Updated resend-email/email-template.ts from email-template.html.");
  }
} catch (error) {
  console.error("Could not build the order notification function; check its handler and HTML template files.", error);
  process.exitCode = 1;
}
